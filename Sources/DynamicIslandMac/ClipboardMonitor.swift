import AppKit
import ImageIO
import Observation
import UniformTypeIdentifiers

@MainActor @Observable final class ClipboardMonitor {
    static let defaultExclusions = ["com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "com.bitwarden.desktop", "com.apple.keychainaccess", "com.dashlane.Dashlane", "com.lastpass.LastPass", "com.apple.Passwords"]
    private(set) var enabled = false
    private(set) var denied = false
    private let store: TrayStore
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let sourceProvider: () -> String?
    private var timer: Timer?
    private var lastChange = 0
    private var ownChange = -1
    private var copyTasks: [UUID: Task<Void, Never>] = [:]
    var onChange: (() -> Void)?
    var exclusionText: String { defaults.string(forKey: "trayExclusions") ?? Self.defaultExclusions.joined(separator: "\n") }
    init(store: TrayStore, pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard, source: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }) { self.store = store; self.pasteboard = pasteboard; self.defaults = defaults; sourceProvider = source }
    nonisolated static func shouldIgnore(types: [String], source: String?, exclusions: Set<String>) -> Bool {
        let privateTypes = Set(["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
        return !privateTypes.isDisjoint(with: types) || source.map { exclusions.contains($0.lowercased()) } == true
    }
    func setExclusions(_ text: String) { defaults.set(text, forKey: "trayExclusions") }
    func start() {
        guard !enabled else { return }; enabled = true; lastChange = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.poll() } }
        timer.tolerance = 0.04; self.timer = timer; RunLoop.main.add(timer, forMode: .common)
        refreshStatus()
    }
    func stop() {
        enabled = false; timer?.invalidate(); timer = nil
        store.cancel(group: "clipboard")
        DiagnosticsModel.shared.update(.clipboard, .degraded, "Clipboard monitoring paused; timer stopped")
    }
    private func accessDenied() -> Bool {
        if #available(macOS 15.4, *) { return pasteboard.accessBehavior == .alwaysDeny }
        return false
    }
    func refreshStatus() {
        denied = accessDenied()
        guard enabled else { return }
        if let error = store.error { DiagnosticsModel.shared.update(.clipboard, .failed, "Tray storage: \(error)"); return }
        DiagnosticsModel.shared.update(.clipboard, denied ? .failed : .ok, denied ? "Allow clipboard access in System Settings → Privacy & Security" : "Text/images/files monitor active · changeCount \(pasteboard.changeCount) · \(store.items.count) items")
    }
    func poll() {
        guard enabled else { return }
        let previouslyDenied = denied; denied = accessDenied()
        if denied { refreshStatus(); if !previouslyDenied { onChange?() }; return }
        if previouslyDenied { lastChange = -1 }
        let count = pasteboard.changeCount
        guard count != lastChange else { return }; lastChange = count
        guard count != ownChange else { return }
        let source = sourceProvider()
        let exclusions = Set(exclusionText.components(separatedBy: .whitespacesAndNewlines).filter { !$0.isEmpty }.map { $0.lowercased() })
        // Check source before touching content, and concealed markers before any data reads.
        guard !Self.shouldIgnore(types: [], source: source, exclusions: exclusions) else { return }
        let types = pasteboard.types?.map(\.rawValue) ?? []
        guard !Self.shouldIgnore(types: types, source: source, exclusions: exclusions) else { return }
        let capturedCount = count
        let completion: (TrayItem?) -> Void = { [weak self] item in
            guard let self, self.enabled else { return }
            if let item { DiagnosticsModel.shared.update(.clipboard, .ok, "Captured \(item.kind.rawValue) · changeCount \(capturedCount) · \(self.store.items.count) items", event: true) }
            self.onChange?()
        }
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue), let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            for url in urls.prefix(100) { store.importItem(.file(url, .file), source: source, completion: completion) }
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            let kind: TrayKind = source == "com.apple.screencaptureui" ? .screenshot : .image
            store.importItem(.image(data, kind), source: source, completion: completion)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            store.importItem(.text(text), source: source, completion: completion)
        } else if !types.isEmpty {
            DiagnosticsModel.shared.update(.clipboard, accessDenied() ? .failed : .degraded, "Clipboard content unavailable or unsupported; check access in Privacy & Security", event: true)
        }
    }
    func copy(_ item: TrayItem, completion: @escaping (Bool) -> Void) {
        if item.kind == .text, let text = item.text {
            pasteboard.clearContents(); let result = pasteboard.setString(text, forType: .string)
            ownChange = pasteboard.changeCount; completion(result); return
        }
        guard let url = item.fileURL else { completion(false); return }
        if item.kind == .file {
            pasteboard.clearContents(); let result = pasteboard.writeObjects([url as NSURL])
            ownChange = pasteboard.changeCount; completion(result); return
        }
        let id = UUID()
        copyTasks[id] = Task { [weak self] in
            let data = await Task.detached(priority: .userInitiated) { () -> Data? in
                guard let source = CGImageSourceCreateWithURL(url as CFURL, nil), let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
                let data = NSMutableData()
                guard let output = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
                CGImageDestinationAddImage(output, image, nil)
                return CGImageDestinationFinalize(output) ? data as Data : nil
            }.value
            guard let self else { return }; self.copyTasks.removeValue(forKey: id)
            guard let data else { completion(false); return }
            self.pasteboard.clearContents(); let success = self.pasteboard.setData(data, forType: .png)
            self.ownChange = self.pasteboard.changeCount; completion(success)
        }
    }
    func openAccessSettings() {
        NSApp.setActivationPolicy(.regular); NSApp.activate(ignoringOtherApps: true)
        // accessBehavior is read-only. Only the user may change the system policy.
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security") { NSWorkspace.shared.open(url) }
    }
}
